// Questions the bot could not answer, and the owner's answers to them
// (RFC 070, BL-231). Pure: no filesystem, no network.
//
// A row the night skipped as `no_honest_answer` carries its blocking
// required questions in `apply_note` ("no_honest_answer: <q1>; <q2>"). This
// module turns those notes into one entry per distinct question (the same
// question asked by several companies is one entry), decides which rows can
// go back to the queue because the owner has answered every blocker, and
// merges the owner's Notion answers into `apply_defaults.json`:
//
//   standing_answers: [{ question, answer, notion_page_id?, question_key? }]  — answered
//   skip_questions:   [{ question, notion_page_id?, question_key? }]          — "skip such jobs"
//
// Entries with `notion_page_id` belong to the Notion Q&A database and are
// replaced on every pull; entries without it are the owner's own and are
// never touched. `question_key` is the key of the form question the entry
// was pushed for, so an answer still matches after the owner rewords the
// Notion title. "<company>" in an answer becomes the form's company.
//
// Question identity = `questionKey(label, company)`: the company's name is
// replaced with "<company>", the trailing required-marker is dropped, case
// and punctuation are ignored. "Why do you want to work at Acme?" asked by
// Acme and "Why do you want to work at Beta?" asked by Beta are one entry
// ("Why do you want to work at <company>?").
//
// Never collected: "prove you are not a bot" checks and "certify that no AI
// was used" questions (`excludedReason`) — the bot never answers those, so
// asking the owner would only fill the database with noise.

const path = require("path");

// State the `questions` command leaves for the morning report:
// profiles/<id>/.apply-state/questions.json =
//   { updated_at, waiting: n, view_url, requeued: [{ key, date, at, questions }] }
const STATE_FILE = path.join(".apply-state", "questions.json");

function statePath(profileRoot) {
  return path.join(profileRoot, STATE_FILE);
}

const COMPANY_PLACEHOLDER = "<company>";
const NO_HONEST_ANSWER = "no_honest_answer";
const OWNER_SKIP_CODE = "owner_skip";
const REQUEUE_NOTE_SUFFIX = "answers";
// Forms the bot never submits (Ashby: invisible bot check, see apply.js
// NO_SUBMIT_ATS): their questions are not collected and the rows stay put.
const NO_SUBMIT_HOST_RE = /(^|\.)ashbyhq\.com$/i;
const KEY_LIMIT = 200;

function str(v) {
  return v === undefined || v === null ? "" : String(v);
}

function escapeRe(s) {
  return String(s).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

// "Acme, Inc." → ["Acme, Inc.", "Acme"] — longest first.
function companyVariants(company) {
  const c = str(company).trim();
  if (c.length < 2) return [];
  const out = new Set([c]);
  const bare = c
    .replace(/[,.]?\s+(inc|llc|ltd|corp|corporation|co|gmbh|plc|pbc|technologies)\.?$/i, "")
    .trim();
  if (bare.length >= 2) out.add(bare);
  return [...out].sort((a, b) => b.length - a.length);
}

// Label as shown on the form, without the required marker and extra spaces.
function cleanLabel(label) {
  let s = str(label).replace(/\s+/g, " ").trim();
  for (let i = 0; i < 3; i++) {
    s = s
      .replace(/\s*\(required\)\s*$/i, "")
      .replace(/[\s*✱]+$/, "")
      .trim();
  }
  return s;
}

function withPlaceholder(text, company) {
  let s = str(text);
  for (const v of companyVariants(company)) {
    const re = new RegExp(`(^|[^A-Za-z0-9])${escapeRe(v)}(?=$|[^A-Za-z0-9])`, "gi");
    s = s.replace(re, (m, pre) => `${pre}${COMPANY_PLACEHOLDER}`);
  }
  return s;
}

// The question as the owner sees it in Notion.
function displayQuestion(label, company) {
  return withPlaceholder(cleanLabel(label), company);
}

// Identity of a question across companies and spellings.
function questionKey(label, company) {
  return withPlaceholder(cleanLabel(label), company)
    .toLowerCase()
    .replace(/<company>/g, " xcompanyx ")
    .replace(/[’']/g, "")
    .replace(/[^a-z0-9]+/g, " ")
    .trim()
    .slice(0, KEY_LIMIT);
}

// "Prove you are human" checks and "no AI was used" certifications.
const BOT_CHECK_RE =
  /\b(not an? (ro)?bot|are you (an? )?(human|robot|bot)|prove (that )?you('re| are) (an? )?human|human verification|captcha|secret (word|code|phrase)|decode the|type the (word|phrase))\b/i;
const AI_TERM_RE =
  /(\bai\b|\ba\.i\.|artificial intelligence|chat ?gpt|\bllms?\b|\bgpt\b|\bclaude\b|\bcopilot\b|\bgenerative\b)/i;
const AI_CERT_RE =
  /\b(certify|attest|affirm|without (the )?(use|help|assistance)|without using|not (used|using)|did ?n[o']t use|no use of|own words|written (entirely )?by (you|yourself|me|myself)|(ai|machine)[- ]generated|generated by|assisted by|with the (help|assistance) of)\b/i;

function excludedReason(label) {
  const t = str(label);
  if (BOT_CHECK_RE.test(t)) return "bot_check";
  if (AI_TERM_RE.test(t) && AI_CERT_RE.test(t)) return "ai_certification";
  return null;
}

// apply_note → { blockers: [label], ownerSkip } for a no_honest_answer
// skip, null for anything else.
function parseBlockers(note) {
  const raw = str(note).trim();
  const m = raw.match(/^no_honest_answer(?:\s*:\s*([\s\S]*))?$/);
  if (!m) return null;
  let detail = str(m[1]).trim();
  let ownerSkip = false;
  if (detail.startsWith(`${OWNER_SKIP_CODE}:`)) {
    ownerSkip = true;
    detail = detail.slice(OWNER_SKIP_CODE.length + 1).trim();
  }
  if (detail === NO_HONEST_ANSWER || detail === "schema_changed") detail = "";
  const seen = new Set();
  const blockers = [];
  for (const part of detail.split(/;\s*/)) {
    const label = part.trim();
    if (!label || seen.has(label)) continue;
    seen.add(label);
    blockers.push(label);
  }
  return { blockers, ownerSkip };
}

// The apply_note for a no_honest_answer row.
function blockerNote(blockers, ownerSkip) {
  const list = (blockers || []).join("; ");
  if (ownerSkip) return `${NO_HONEST_ANSWER}: ${OWNER_SKIP_CODE}: ${list}`;
  return list ? `${NO_HONEST_ANSWER}: ${list}` : NO_HONEST_ANSWER;
}

function requeueNote(date) {
  return `requeued:${date} ${REQUEUE_NOTE_SUFFIX}`;
}

function hostOf(url) {
  try {
    return new URL(str(url)).hostname;
  } catch {
    return "";
  }
}

// Rows the owner could unblock: skipped as no_honest_answer, still To Apply,
// never applied, not on a form the bot never submits.
function isBlockedRow(app) {
  if (!app || str(app.apply_state).trim() !== "skipped") return false;
  if (str(app.status) !== "To Apply" || str(app.applied_date).trim()) return false;
  if (NO_SUBMIT_HOST_RE.test(hostOf(app.url))) return false;
  return parseBlockers(app.apply_note) !== null;
}

// apply_defaults → { answers: Map<key, answer>, skips: Set<key> }.
function answerIndex(applyDefaults) {
  const ad = applyDefaults && typeof applyDefaults === "object" ? applyDefaults : {};
  // Both the question text and, for Notion entries, the key of the form
  // question it was pushed for (the owner may have reworded the title).
  const keysOf = (x) => [questionKey(x.question, null), str(x.question_key).trim()].filter(Boolean);
  const answers = new Map();
  for (const sa of Array.isArray(ad.standing_answers) ? ad.standing_answers : []) {
    if (!sa || !str(sa.question).trim() || !str(sa.answer).trim()) continue;
    for (const k of keysOf(sa)) if (!answers.has(k)) answers.set(k, str(sa.answer));
  }
  const skips = new Set();
  for (const sq of Array.isArray(ad.skip_questions) ? ad.skip_questions : []) {
    if (sq && str(sq.question).trim()) for (const k of keysOf(sq)) skips.add(k);
  }
  return { answers, skips };
}

// The owner's standing answer to a form question, or null. "<company>" in
// the answer becomes the form's company.
function findStandingAnswer(index, label, company) {
  if (!index) return null;
  const k = questionKey(label, company);
  const answer = (k && index.answers.get(k)) || null;
  if (!answer || !str(company).trim()) return answer;
  return answer.replace(/<company>/gi, str(company).trim());
}

function isSkipQuestion(index, label, company) {
  if (!index) return false;
  const k = questionKey(label, company);
  return Boolean(k) && index.skips.has(k);
}

// Pure: what to do with every blocked row.
//   requeue:   every blocker has an owner answer → back to the queue
//   ownerSkip: a blocker is on the owner's skip list → stays skipped,
//              note "no_honest_answer: owner_skip: …"
//   waiting:   some blockers have no answer yet → their questions go to Notion
//   stuck:     no blocker labels recorded, or a blocker the bot never
//              answers (bot check / AI certification) → stays as it is
// Each item: { app, blockers, note } (note = the apply_note it should carry).
function planRows(apps, applyDefaults) {
  const index = answerIndex(applyDefaults);
  const out = { requeue: [], ownerSkip: [], waiting: [], stuck: [] };
  for (const app of apps || []) {
    if (!isBlockedRow(app)) continue;
    const { blockers } = parseBlockers(app.apply_note);
    const company = app.companyName;
    if (!blockers.length) {
      out.stuck.push({ app, blockers, note: str(app.apply_note), why: "no_labels" });
      continue;
    }
    if (blockers.some((b) => isSkipQuestion(index, b, company))) {
      out.ownerSkip.push({ app, blockers, note: blockerNote(blockers, true) });
      continue;
    }
    const open = blockers.filter((b) => !findStandingAnswer(index, b, company));
    if (!open.length) {
      out.requeue.push({ app, blockers, note: null });
      continue;
    }
    if (open.some((b) => excludedReason(b))) {
      out.stuck.push({ app, blockers, note: blockerNote(blockers, false), why: "excluded" });
      continue;
    }
    out.waiting.push({ app, blockers, open, note: blockerNote(blockers, false) });
  }
  return out;
}

// Pure: waiting rows → one entry per distinct open question.
//   [{ key, question, rows: [{ key, company, title, url }] }]
function groupQuestions(waiting) {
  const groups = new Map();
  for (const item of waiting || []) {
    const app = item.app;
    for (const label of item.open || []) {
      if (excludedReason(label)) continue;
      const key = questionKey(label, app.companyName);
      if (!key) continue;
      let g = groups.get(key);
      if (!g) {
        g = { key, question: displayQuestion(label, app.companyName), rows: [] };
        groups.set(key, g);
      }
      if (!g.rows.some((r) => r.key === app.key)) {
        g.rows.push({
          key: str(app.key),
          company: str(app.companyName),
          title: str(app.title),
          url: str(app.url),
        });
      }
    }
  }
  return [...groups.values()].sort(
    (a, b) => b.rows.length - a.rows.length || a.question.localeCompare(b.question)
  );
}

// "Company — Title — URL" per job, for the Notion entry.
function jobsText(group) {
  return (group.rows || [])
    .map((r) => [r.company, r.title, r.url].filter(Boolean).join(" — "))
    .sort()
    .join("\n");
}

// Pure: merge the owner's Notion entries into apply_defaults.
//   entries: Q&A rows ({ pageId, question, answer, status }) — only those with
//            status ANSWERED (and a non-empty answer) or SKIP count.
// Returns { next, answers, skips, removed, changed }.
function mergeOwnerAnswers(applyDefaults, entries, statuses) {
  const ad = applyDefaults && typeof applyDefaults === "object" ? applyDefaults : {};
  const answered = [];
  const skipped = [];
  for (const e of entries || []) {
    if (!e || !e.pageId || !str(e.question).trim()) continue;
    const key = str(e.questionKey).trim();
    const tag = { notion_page_id: e.pageId, ...(key ? { question_key: key } : {}) };
    if (e.status === statuses.answered && str(e.answer).trim()) {
      answered.push({ question: str(e.question).trim(), answer: str(e.answer).trim(), ...tag });
    } else if (e.status === statuses.skip) {
      skipped.push({ question: str(e.question).trim(), ...tag });
    }
  }
  const own = (list) => (Array.isArray(list) ? list : []).filter((x) => !(x && x.notion_page_id));
  const fromNotion = (list) =>
    (Array.isArray(list) ? list : []).filter((x) => x && x.notion_page_id);
  const prevAnswers = fromNotion(ad.standing_answers);
  const prevSkips = fromNotion(ad.skip_questions);
  const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);
  const byId = (list) => new Map(list.map((x) => [x.notion_page_id, x]));
  const prevA = byId(prevAnswers);
  const prevS = byId(prevSkips);
  const nextA = byId(answered);
  const nextS = byId(skipped);
  const removed = [
    ...prevAnswers.filter((x) => !nextA.has(x.notion_page_id)),
    ...prevSkips.filter((x) => !nextS.has(x.notion_page_id)),
  ];
  const changed = !same(prevAnswers, answered) || !same(prevSkips, skipped);
  const next = { ...ad };
  const standing = [...own(ad.standing_answers), ...answered];
  const skipList = [...own(ad.skip_questions), ...skipped];
  if (standing.length || ad.standing_answers !== undefined) next.standing_answers = standing;
  if (skipList.length || ad.skip_questions !== undefined) next.skip_questions = skipList;
  return {
    next,
    answers: answered.map((a) => ({ ...a, new: !prevA.has(a.notion_page_id) })),
    skips: skipped.map((s) => ({ ...s, new: !prevS.has(s.notion_page_id) })),
    removed,
    changed,
  };
}

